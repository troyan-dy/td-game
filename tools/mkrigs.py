"""tools/mkrigs.py — tools/rigs.json (суставы в координатах листа) → live/rigs.js (суставы в px текстур после prep).
Ground G и высота H фигуры берутся из rigs.json (ground: точка между ступнями, top: верх шлема)."""
import json
R = json.load(open('tools/rigs.json', encoding='utf-8'))
s = open('live/assets.js', encoding='utf-8').read(); A = json.loads(s[s.index('{'):s.rindex('}') + 1])
out = {}
for n, cfg in R.items():
    if any(p['tex'] not in A for p in cfg['parts']): continue
    gx, gy = cfg['ground']; H = gy - cfg['top']
    parts = []
    for p in cfg['parts']:
        a = A[p['tex']]; c0 = a['crop'][:2]; k = a.get('scale', 1)
        jt = [(p['joint'][0] - p['box'][0] - c0[0]) * k, (p['joint'][1] - p['box'][1] - c0[1]) * k]
        parts.append({'tex': p['tex'], 'sc': p.get('scale', 1) / k, 'jt': [round(v, 1) for v in jt], 'at': [p['at'][0] - gx, p['at'][1] - gy],
                      'swing': p.get('swing', 0), 'phase': p.get('phase', 0), 'rest': p.get('rest', 0), 'dark': p.get('dark', 1), 'kind': p.get('kind', 'limb'),
                      'r': p.get('r', 0)})
    out[n] = {'H': H, 'stride': cfg.get('stride', 22), 'parts': parts}
    if 'light' in cfg: out[n]['light'] = [[l[0] - gx, l[1] - gy] for l in cfg['light']]
open('live/rigs.js', 'w', encoding='utf-8').write('// generated by tools/mkrigs.py from tools/rigs.json — cut-out rigs of enemies\nwindow.RIGS = ' + json.dumps(out) + ';\n')
print({k: len(v['parts']) for k, v in out.items()})
