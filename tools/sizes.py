"""tools/sizes.py — пишет live/sizes.js (размер спрайтов на экране, view px) из live/assets.js.
Башни: один масштаб на лист, уровень 3 = TOWER_L3 px в высоту. Враги: по высоте из ENEMY_H. Остальное — из таблицы FIXED."""
import json, re
s = open('live/assets.js', encoding='utf-8').read(); A = json.loads(s[s.index('{'):s.rindex('}') + 1])
TOWER_L3 = {'bones': 108, 'spirits': 116, 'plague': 108, 'dark': 128}
ENEMY_H = {'militia': 34, 'knight': 36, 'priest': 38, 'cart': 50, 'paladin': 62}
FIXED_W = {'pad': 74}
out = {}
for t, h3 in TOWER_L3.items():
    if f'tw_{t}_3' in A: k = h3 / A[f'tw_{t}_3']['h']
    elif f'tw_{t}_1' in A: k = h3 * 0.58 / A[f'tw_{t}_1']['h']   # нет листа уровней: уровень 1 = 58% от высоты уровня 3
    else: continue
    for l in (1, 2, 3):
        n = f'tw_{t}_{l}'
        if n in A: out[n] = [round(A[n]['w'] * k), round(A[n]['h'] * k)]
for n, a in A.items():
    m = re.match(r'en_(\w+)$', n)
    if m and m.group(1) in ENEMY_H: h = ENEMY_H[m.group(1)]; out[n] = [round(a['w'] * h / a['h']), h]
    if n in FIXED_W: w = FIXED_W[n]; out[n] = [w, round(a['h'] * w / a['w'])]
open('live/sizes.js', 'w', encoding='utf-8').write('// generated by tools/sizes.py — display size [w, h] in view px\nwindow.SIZES = ' + json.dumps(out) + ';\n')
print(out)
